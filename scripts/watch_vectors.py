#!/usr/bin/env python3
"""Convert crypto_vectors.json into a Monkey C test-source file.

The Connect IQ test framework has no JSON parser, so the committed Kotlin
vectors are re-emitted as a generated Monkey C class holding hex strings;
the test suite decodes them and runs every fixture through the watch's
Hkdf / AesCcm / SessionCrypto ports.

Input fixtures (app/src/test/resources/crypto_vectors.json, produced by
gen_vectors.py): ccm_no_aad, ccm_aad, session_enc, hkdf_login,
hkdf_rfc5869_tc1.

Usage:
    python scripts/watch_vectors.py > watch/test/vectors_generated.mc
"""

import json
import sys
from pathlib import Path

VECTORS = Path(__file__).resolve().parent.parent / "app" / "src" / "test" / "resources" / "crypto_vectors.json"


def mc_string(value: str) -> str:
    return '"' + value + '"'


def fixture_dict(fixture: dict) -> str:
    """One fixture as a Monkey C dictionary literal; None becomes null."""
    entries = []
    for key, value in fixture.items():
        if isinstance(value, bool):
            rendered = "true" if value else "false"
        elif value is None:
            rendered = "null"
        elif isinstance(value, int):
            rendered = str(value)
        elif isinstance(value, str):
            rendered = mc_string(value)
        else:
            raise SystemExit(f"fixture {fixture['name']}: unexpected {key}={value!r}")
        entries.append(f"                {mc_string(key)} => {rendered}")
    return "{\n" + ",\n".join(entries) + "\n            }"


def main() -> None:
    fixtures = json.loads(VECTORS.read_text(encoding="utf-8"))
    wanted = ["ccm_no_aad", "ccm_aad", "session_enc", "hkdf_login", "hkdf_rfc5869_tc1"]
    by_name = {f["name"]: f for f in fixtures}
    missing = [name for name in wanted if name not in by_name]
    if missing:
        raise SystemExit(f"missing fixtures in {VECTORS}: {missing}")

    # Sort keys for a stable, reviewable diff; keep "name" first.
    dicts = []
    for name in wanted:
        fixture = by_name[name]
        ordered = {"name": fixture["name"]}
        ordered.update({k: fixture[k] for k in sorted(fixture) if k != "name"})
        dicts.append(fixture_dict(ordered))

    body = ",\n".join(f"            {d}" for d in dicts)
    sys.stdout.write(
        "//! GENERATED by scripts/watch_vectors.py from\n"
        "//! app/src/test/resources/crypto_vectors.json - DO NOT EDIT.\n"
        "\n"
        "import Toybox.Lang;\n"
        "\n"
        "class VectorsGenerated {\n"
        "    static function fixtures() as Array<Dictionary<String, Object>> {\n"
        "        return [\n"
        f"{body}\n"
        "        ];\n"
        "    }\n"
        "}\n"
    )


if __name__ == "__main__":
    main()
